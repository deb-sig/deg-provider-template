export const locales = ['en', 'zh-CN', 'zh-TW'];
export function detectLocale(saved, languages = []) {
  if (locales.includes(saved)) return saved;
  for (const language of languages) {
    const tag = language.toLowerCase();
    if (/^zh(?:-|$)/.test(tag)) return /(?:hant|tw|hk|mo)/.test(tag) ? 'zh-TW' : 'zh-CN';
    // Browser's first preferred language determines the default.
    return 'en';
  }
  return 'en';
}
export function translate(locale, key) { return messages[locale]?.[key] ?? messages.en[key] ?? key; }
